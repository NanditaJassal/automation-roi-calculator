import pandas as pd
import random

random.seed(42)

months = pd.date_range("2025-01-01", periods=12, freq="MS")
data = []

for month in months:
    volume = random.randint(3500, 5500)

    data.append({
        "month": month.strftime("%Y-%m"),
        "invoice_volume": volume,
        "manual_minutes_per_invoice": 4,
        "automation_rate": 0.70,
        "exception_rate": 0.10,
        "labour_cost_per_hour_nzd": 35,
        "monthly_software_cost_nzd": 1200,
        "setup_cost_nzd": 15000
    })

df = pd.DataFrame(data)

df.to_csv("automation_roi_dataset.csv", index=False)

print(df.head())
print("Total records:", len(df))

